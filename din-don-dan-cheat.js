const start = Date.now();

function playNote(note) {
    const keyMappings = {
        "u": "ArrowUp",
        "d": "ArrowDown",
        "l": "ArrowLeft",
        "r": "ArrowRight"
    };
    
    const downEvent = new KeyboardEvent("keydown", { key: keyMappings[note.key] });
    const upEvent = new KeyboardEvent("keyup", { key: keyMappings[note.key] });
    
    document.dispatchEvent(downEvent);
    setTimeout(() => {
        document.dispatchEvent(upEvent);
    }, 100);

    note.played = true;
}

setInterval(() => {
    const currTime = (Date.now() - start) / 1000;

    for (let i = 0; i < notes.length; i++) {
        const note = notes[i];
        if (!note.played && currTime > note.time) {
            playNote(note);
        }
    }
}, 1000/60);
